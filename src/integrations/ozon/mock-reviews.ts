//   сыворотка с витамином C «потемнела»        → старая партия, ротация склада;
//   помада Coral «цвет не как на фото»         → контент, а не плохой оттенок;
//   ретинол «подозрительно дёшево, подделка?»  → цена как сигнал качества.
// У остальных — обычный фон: в основном хорошие, изредка случайный негатив.
//
// Детерминированно от артикула. В живом режиме отзывы отдаёт Seller API
// (/v1/review/list, нужна подписка Premium Plus) — не проверено, ключей нет.


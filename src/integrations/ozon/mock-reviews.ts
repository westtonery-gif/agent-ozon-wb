export function reviewsFor(p: OzonProduct): Review[] {
  const h = seedOf(`reviews:${p.offer_id}`);
  const total = Math.min(30, p.reviews_count ?? 0);
  const out: Review[] = [];

  const scripted = SCRIPTED[p.offer_id] ?? [];
  scripted.forEach(([ago, rating, text], i) => {
    out.push({ id: `${p.offer_id}-n${i}`, sku: p.offer_id, date: iso(ago), rating, text });
  });

  // Фон: в основном хорошие, у товаров без истории — изредка случайный негатив.
  const background = Math.max(0, total - scripted.length);
  const randomNegatives = scripted.length ? 0 : (h % 3 === 0 ? 1 : 0);
  for (let i = 0; i < background; i++) {
    const negative = i < randomNegatives;
    const ago = 1 + ((h >>> (i % 24)) % 59);
    out.push({
      id: `${p.offer_id}-p${i}`,
      sku: p.offer_id,
      date: iso(ago),
      rating: negative ? 3 : 4 + ((h >>> i) & 1),
      text: negative
        ? BACKGROUND_NEGATIVE[(h >>> i) % BACKGROUND_NEGATIVE.length]
        : POSITIVE[(h >>> (i * 2)) % POSITIVE.length],
    });
  }
  return out.sort((a, b) => b.date.localeCompare(a.date));
}
